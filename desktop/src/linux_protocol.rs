    #[test]
    fn startup_migration_is_idempotent_and_preserves_unknown_files() {
        let directory = test_directory("startup");
        let icons = directory.join("icons");
        let canonical = directory.join(DESKTOP_ID);
        let old_executable = directory.join("old-panita-client.AppImage");
        let current_executable = directory.join("panita-client.AppImage");
        let current_entry =
            desktop_entry(&current_executable).unwrap_or_else(|_| panic!("current entry"));
        std::fs::write(
            &canonical,
            format!(
                "{HIDDEN_LEGACY_PREFIX}{}{HIDDEN_LEGACY_SUFFIX}",
                old_executable.display()
            ),
        )
        .unwrap_or_else(|_| panic!("old canonical entry"));
        let callback_test = directory.join(CALLBACK_TEST_ID);
        std::fs::write(
            &callback_test,
            format!(
                "{OWNED_PREFIX}{}{CALLBACK_TEST_SUFFIX}",
                old_executable.display()
            ),
        )
        .unwrap_or_else(|_| panic!("old callback entry"));

        assert!(
            migrate_files(&current_executable, &directory, &icons)
                .unwrap_or_else(|_| panic!("first migration"))
        );
        assert!(!callback_test.exists());
        assert_eq!(
            std::fs::read_to_string(&canonical).ok().as_deref(),
            Some(current_entry.as_str())
        );
        assert_eq!(
            std::fs::read(icons.join(ICON_NAME)).ok().as_deref(),
            Some(ICON)
        );
        assert!(
            !migrate_files(&current_executable, &directory, &icons)
                .unwrap_or_else(|_| panic!("idempotent migration"))
        );

        let custom_entry = "[Desktop Entry]\nName=Custom launcher\n";
        std::fs::write(&canonical, custom_entry).unwrap_or_else(|_| panic!("custom entry"));
        assert!(migrate_files(&current_executable, &directory, &icons).is_err());
        assert_eq!(
            std::fs::read_to_string(&canonical).ok().as_deref(),
            Some(custom_entry)
        );

        std::fs::write(&canonical, &current_entry)
            .unwrap_or_else(|_| panic!("restore canonical entry"));
        let custom_icon = b"custom icon";
        std::fs::write(icons.join(ICON_NAME), custom_icon)
            .unwrap_or_else(|_| panic!("custom icon"));
        assert!(migrate_files(&current_executable, &directory, &icons).is_err());
        assert_eq!(
            std::fs::read(icons.join(ICON_NAME)).ok().as_deref(),
            Some(custom_icon.as_slice())
        );

        std::fs::write(icons.join(ICON_NAME), ICON).unwrap_or_else(|_| panic!("restore icon"));
        std::fs::create_dir(&callback_test).unwrap_or_else(|_| panic!("non-regular entry"));
        assert!(
            !migrate_files(&current_executable, &directory, &icons)
                .unwrap_or_else(|_| panic!("non-regular preservation"))
        );
        assert!(callback_test.is_dir());

        std::fs::remove_dir_all(directory).unwrap_or_else(|_| panic!("test cleanup"));
    }

