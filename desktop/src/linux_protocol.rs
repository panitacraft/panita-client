//! Use the package's desktop-file ID so a user override remains one application.
use std::path::Path;

const DESKTOP_ID: &str = "Panita Client.desktop";
const LEGACY_ID: &str = "com.panitacraft.client.desktop";
const MIME: &str = "x-scheme-handler/panitacraft";
const LEGACY_PREFIX: &str = "[Desktop Entry]\nType=Application\nName=Panita Client\nExec=\"";
const LEGACY_SUFFIX: &str =
    "\" %u\nTerminal=false\nNoDisplay=true\nMimeType=x-scheme-handler/panitacraft;\n";

fn desktop_entry(executable: &Path) -> Result<String, ()> {
    let executable = executable.to_str().ok_or(())?;
    if !Path::new(executable).is_absolute() || executable.contains(['\n', '\r', '\0']) {
        return Err(());
    }
    // Desktop Entry string escaping is applied after Exec argument escaping.
    let escaped = executable
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('`', "\\`")
        .replace('$', "\\$")
        .replace('%', "%%")
        .replace('\\', "\\\\");
    Ok(format!(
        "[Desktop Entry]\nType=Application\nName=Panita Client\nExec=\"{escaped}\" %u\nIcon=panita-desktop\nStartupWMClass=panita-desktop\nTerminal=false\nMimeType={MIME};\nX-PanitaClient-Owner=com.panitacraft.client\n"
    ))
}

fn remove_legacy_entry(directory: &Path) -> std::io::Result<()> {
    let path = directory.join(LEGACY_ID);
    let content = match std::fs::read_to_string(&path) {
        Ok(content) => content,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error),
    };
    // Only migrate the exact format previously generated by this launcher.
    // Preserve edited entries and unrelated registrations.
    if let Some(executable) = content
        .strip_prefix(LEGACY_PREFIX)
        .and_then(|rest| rest.strip_suffix(LEGACY_SUFFIX))
        && !executable.is_empty()
        && !executable.contains(['\n', '\r', '\0'])
    {
        std::fs::remove_file(path)?;
    }
    Ok(())
}

#[cfg(target_os = "linux")]
pub(super) fn register(executable: &Path, directory: &Path) -> Result<(), ()> {
    let entry = desktop_entry(executable)?;
    std::fs::create_dir_all(directory).map_err(|_| ())?;
    std::fs::write(directory.join(DESKTOP_ID), entry).map_err(|_| ())?;
    let status = std::process::Command::new("xdg-mime")
        .args(["default", DESKTOP_ID, MIME])
        .output()
        .map_err(|_| ())?;
    if !status.status.success() {
        return Err(());
    }
    remove_legacy_entry(directory).map_err(|_| ())?;
    // Refresh cached associations when desktop-file-utils is installed.
    // xdg-mime remains required; this optional cache tool is not a dependency.
    let _ = std::process::Command::new("update-desktop-database")
        .arg(directory)
        .output();
    let query = std::process::Command::new("xdg-mime")
        .args(["query", "default", MIME])
        .output()
        .map_err(|_| ())?;
    if !query.status.success() || String::from_utf8_lossy(&query.stdout).trim() != DESKTOP_ID {
        return Err(());
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn desktop_entry_quotes_paths_and_rejects_invalid_input() {
        let path = std::env::temp_dir().join("Panita Client 100%.AppImage");
        let entry = desktop_entry(&path).unwrap_or_else(|_| panic!("absolute executable"));
        assert!(entry.contains("Panita Client 100%%.AppImage\" %u\n"));
        assert!(!entry.contains("NoDisplay=true"));
        assert!(entry.contains("X-PanitaClient-Owner=com.panitacraft.client\n"));
        assert!(desktop_entry(Path::new("relative")).is_err());
        assert!(desktop_entry(&std::env::temp_dir().join("bad\npath")).is_err());
    }

    #[test]
    fn migration_removes_only_the_launchers_exact_legacy_format() {
        let directory = std::env::temp_dir().join(format!(
            "panita-desktop-migration-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap_or_else(|_| panic!("system clock"))
                .as_nanos()
        ));
        std::fs::create_dir(&directory).unwrap_or_else(|_| panic!("test directory"));
        let legacy = directory.join(LEGACY_ID);
        let canonical = directory.join(DESKTOP_ID);
        std::fs::write(&canonical, "canonical").unwrap_or_else(|_| panic!("canonical entry"));
        std::fs::write(
            &legacy,
            format!("{LEGACY_PREFIX}/usr/bin/panita-desktop{LEGACY_SUFFIX}"),
        )
        .unwrap_or_else(|_| panic!("legacy entry"));
        assert!(remove_legacy_entry(&directory).is_ok());
        assert!(!legacy.exists());
        std::fs::write(&legacy, "[Desktop Entry]\nName=Custom handler\n")
            .unwrap_or_else(|_| panic!("custom entry"));
        assert!(remove_legacy_entry(&directory).is_ok());
        assert!(legacy.exists());
        assert_eq!(
            std::fs::read_to_string(canonical).ok().as_deref(),
            Some("canonical")
        );
        std::fs::remove_dir_all(directory).unwrap_or_else(|_| panic!("test cleanup"));
    }
}
